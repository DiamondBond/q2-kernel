#define INGENIC_DMA_TSZ_POLICY_COUNT ARRAY_SIZE(ingenic_dma_tsz_policies)

enum ingenic_dma_tsz_mode
ingenic_dma_get_tsz_mode(unsigned int controller_bus,
				 unsigned int request_type)
{
	unsigned int i;

	for (i = 0; i < INGENIC_DMA_TSZ_POLICY_COUNT; i++)
		if (ingenic_dma_tsz_policies[i].controller_bus == controller_bus &&
		    ingenic_dma_tsz_policies[i].request_type == request_type)
			return ingenic_dma_tsz_policies[i].tsz_mode;

	return INGENIC_DMA_TSZ_AUTONOMOUS;
}
EXPORT_SYMBOL_GPL(ingenic_dma_get_tsz_mode);

