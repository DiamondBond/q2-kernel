static int panel_dev_probe(struct mipi_dsim_lcd_device *dsim_dev)
{
	struct hx_c149hax01 *lcd;

	lcd = devm_kzalloc(&dsim_dev->dev, sizeof(struct hx_c149hax01), GFP_KERNEL);
	if (!lcd)
	{
		dev_err(&dsim_dev->dev, "failed to allocate fitipower_hx_c149hax01 structure.\n");
		return -ENOMEM;
	}

	lcd->dsim_dev = dsim_dev;
	lcd->dev = &dsim_dev->dev;

	lcd->ld = lcd_device_register("fitipower_hx_c149hax01", lcd->dev, lcd,
	                              &panel_lcd_ops);
	if (IS_ERR(lcd->ld))
	{
		dev_err(lcd->dev, "failed to register lcd ops.\n");
		return PTR_ERR(lcd->ld);
	}

	dev_set_drvdata(&dsim_dev->dev, lcd);
	dev_dbg(lcd->dev, "probed fitipower_hx_c149hax01 panel driver.\n");

	panel->dsim_dev = dsim_dev;
	return 0;
}

