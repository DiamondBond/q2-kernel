/*
* @panel_probe

* 	1. Register to ingenicfb.
* 	2. Register to lcd.
* 	3. Register to backlight if possible.

* @pdev

* @Return -
*/
static int panel_probe(struct platform_device *pdev)
{
	struct fw050_panel_dev *panel_dev;
	int ret = 0;
	PANEL_DEBUG_MSG("enter %s %d \n",__func__, __LINE__);

	panel_dev = kzalloc(sizeof(struct fw050_panel_dev), GFP_KERNEL);
	if(panel_dev == NULL) {
		dev_err(&pdev->dev, "Faile to alloc memory!");
		return -ENOMEM;
	}
	panel_dev->dev = &pdev->dev;

	/* 从模板复制出当前设备实例自己的 lcd_panel 和 DSI 配置。 */
	panel_dev->lcd_panel = lcd_panel_template;
	panel_dev->dsi_pdata = jzdsi_pdata_template[0];
	panel_dev->lcd_panel.dsi_pdata = &panel_dev->dsi_pdata;
	panel_dev->tft_config = fw050_cfg_template;
	panel_dev->lcd_panel.tft_config = &panel_dev->tft_config;

	/* DSI 回调通过 platform_data 找回当前 panel_dev，不再依赖全局 panel。 */
	panel_dev->dsim_lcd_dev.name = "fitipower_fw050-lcd";
	panel_dev->dsim_lcd_dev.id = 0;
	panel_dev->dsim_lcd_dev.platform_data = panel_dev;
	panel_dev->dsim_dev = &panel_dev->dsim_lcd_dev;

	dev_set_drvdata(&pdev->dev, panel_dev);

	ret = of_panel_parse(&pdev->dev);
	if(ret < 0) {
		goto err_of_parse;
	}

	mipi_dsi_register_lcd_device(&panel_dev->dsim_lcd_dev);
	mipi_dsi_register_lcd_driver(&panel_dev_dsim_ddi_driver);
#if 0
	ret = ingenic_lcd_panel_register(&pdev->dev, &panel_dev->lcd_panel);
	if(ret < 0) {
		dev_err(&pdev->dev, "Failed to register common lcd panel: %d\n", ret);
		goto err_of_parse;
	}
#else
	ret = ingenicfb_register_panel(&panel_dev->lcd_panel);
	if(ret < 0) {
		dev_err(&pdev->dev, "Failed to register lcd panel!\n");
		goto err_of_parse;
	}
#endif
	return 0;

err_of_parse:
	panel_dev_release_gpios(panel_dev);

	kfree(panel_dev);
	return ret;
}

static int panel_remove(struct platform_device *pdev)
{
	struct fw050_panel_dev *panel_dev = dev_get_drvdata(&pdev->dev);

	ingenic_lcd_panel_unregister(&pdev->dev);
	panel_dev_release_gpios(panel_dev);
	dev_set_drvdata(&pdev->dev, NULL);
	kfree(panel_dev);
	return 0;
}

