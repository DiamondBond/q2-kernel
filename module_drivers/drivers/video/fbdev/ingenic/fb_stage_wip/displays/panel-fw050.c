static void panel_dev_release_gpios(struct fw050_panel_dev *panel_dev)
{
	if(!panel_dev || !panel_dev->gpios_requested)
		return;

	/* 读 ID 失败的候选屏必须释放 GPIO，避免下一个候选申请失败。 */
	if(gpio_is_valid(panel_dev->lcd_pwm.gpio))
		gpio_direction_output(panel_dev->lcd_pwm.gpio, !panel_dev->lcd_pwm.active_level);
	if(gpio_is_valid(panel_dev->vdd_en.gpio))
		gpio_direction_output(panel_dev->vdd_en.gpio, !panel_dev->vdd_en.active_level);

	if(gpio_is_valid(panel_dev->lcd_pwm.gpio))
		gpio_free(panel_dev->lcd_pwm.gpio);
	if(gpio_is_valid(panel_dev->rst.gpio))
		gpio_free(panel_dev->rst.gpio);
	if(gpio_is_valid(panel_dev->vdd_en.gpio))
		gpio_free(panel_dev->vdd_en.gpio);

	panel_dev->gpios_requested = false;
}

static int panel_dev_request_gpios(struct fw050_panel_dev *panel_dev)
{
	int ret;

	if(!panel_dev)
		return -EINVAL;

	if(panel_dev->gpios_requested)
		return 0;

	/* 多个候选 panel 共用 GPIO，不能在 platform probe 阶段提前占用。 */
	if(gpio_is_valid(panel_dev->rst.gpio)) {
		ret = gpio_request_one(panel_dev->rst.gpio, GPIOF_DIR_OUT, "rst");
		if(ret < 0) {
			dev_err(panel_dev->dev, "Failed to request rst pin!\n");
			return ret;
		}
		gpio_direction_output(panel_dev->rst.gpio, panel_dev->rst.active_level);
	}

	if(gpio_is_valid(panel_dev->vdd_en.gpio)) {
		ret = gpio_request_one(panel_dev->vdd_en.gpio, GPIOF_DIR_OUT, "vdd_en");
		if(ret < 0) {
			dev_err(panel_dev->dev, "Failed to request vdd_en pin!\n");
			goto err_request_vdd;
		}
		gpio_direction_output(panel_dev->vdd_en.gpio, panel_dev->vdd_en.active_level);
	}

	if(gpio_is_valid(panel_dev->lcd_pwm.gpio)) {
		ret = gpio_request_one(panel_dev->lcd_pwm.gpio, GPIOF_DIR_OUT, "lcd-pwm");
		if(ret < 0) {
			dev_err(panel_dev->dev, "Failed to request lcd-pwm pin!\n");
			goto err_request_pwm;
		}
	}

	panel_dev->gpios_requested = true;
	return 0;

err_request_pwm:
	if(gpio_is_valid(panel_dev->vdd_en.gpio))
		gpio_free(panel_dev->vdd_en.gpio);
err_request_vdd:
	if(gpio_is_valid(panel_dev->rst.gpio))
		gpio_free(panel_dev->rst.gpio);
	return ret;
}

static void panel_dev_power_on(struct mipi_dsim_lcd_device *dsim_dev, int power)
{
	struct fw050_panel_dev *panel_dev = fw050_to_panel(dsim_dev);
	struct board_gpio *vdd_en;
	struct board_gpio *rst;
	struct board_gpio *lcd_te;
	struct board_gpio *pwm;
	PANEL_DEBUG_MSG("enter %s %d \n",__func__, __LINE__);

	if (!panel_dev)
		return;

	/* bootarg 指定 panel 时可能跳过 read_id，这里补申请 GPIO 保持旧用法兼容。 */
	if(panel_dev_request_gpios(panel_dev) < 0)
		return;

	vdd_en = &panel_dev->vdd_en;
	rst = &panel_dev->rst;
	lcd_te = &panel_dev->lcd_te;
	pwm = &panel_dev->lcd_pwm;

	if(gpio_is_valid(vdd_en->gpio))
		gpio_direction_output(vdd_en->gpio, vdd_en->active_level);
	if(gpio_is_valid(pwm->gpio))
		gpio_direction_output(pwm->gpio, pwm->active_level);

	if (gpio_is_valid(lcd_te->gpio)) {
		gpio_direction_input(lcd_te->gpio);
	}
	msleep(50);
	if(gpio_is_valid(rst->gpio)) {
		gpio_direction_output(rst->gpio, 0);
		msleep(10);
		gpio_direction_output(rst->gpio, 1);
		msleep(120);
	}

	panel_dev->power = power;
}

static int panel_dev_read_id(struct mipi_dsim_lcd_device *dsim_dev)
{
	unsigned char buf[3] = {-1,-1,-1};
	struct fw050_panel_dev *panel_dev = fw050_to_panel(dsim_dev);
	struct dsi_master_ops *ops;

	struct dsi_cmd_packet data_to_send0 = {0x14, 0xDA, 0x0};
	struct dsi_cmd_packet data_to_send1 = {0x14, 0xDB, 0x0};
	struct dsi_cmd_packet data_to_send2 = {0x14, 0xDC, 0x0};
	int ret = 0;
	int panel_id = 0;

	if(!panel_dev || !dsim_dev || !dsim_dev->master)
		return -EINVAL;

	ret = panel_dev_request_gpios(panel_dev);
	if(ret < 0)
		return ret;

	ops = dsim_dev->master->master_ops;
	panel_dev_power_on(dsim_dev, 1);
	ret = ops->cmd_read(dsim_dev->master, data_to_send0, &buf[0], 1);
	ret = ops->cmd_read(dsim_dev->master, data_to_send1, &buf[1], 1);
	ret = ops->cmd_read(dsim_dev->master, data_to_send2, &buf[2], 1);
	panel_dev_power_on(dsim_dev, 0);

	panel_id = (buf[0] << 16) + (buf[1] << 8) + buf[2];
	printk("----------%s, (%d) id[0]: %x id[1]: %x, id[2]: %x, id:%08x \n", __func__, __LINE__, buf[0], buf[1], buf[2], panel_id);

	if(panel_id == PANEL_FW050_ID)
		return 0;

	/* ID 不匹配时释放 GPIO，让下一个候选 panel 可以继续读 ID。 */
	panel_dev_release_gpios(panel_dev);
	return -ENODEV;
}

static int panel_dev_panel_init(struct fw050_panel_dev *lcd)
{
	int ret = 0;
	struct dsi_master_ops *ops = lcd_to_master_ops(lcd);
	struct dsi_device *dsi = lcd_to_master(lcd);
	int  i;
	int num_of_param;
	struct dsi_cmd_packet *param_list = NULL;

	if(dsi->video_config->no_of_lanes == 2){
		param_list = &fitipower_fw050_720_1280_2lane_cmd_list[0];
		num_of_param = ARRAY_SIZE(fitipower_fw050_720_1280_2lane_cmd_list);
	} else {
		param_list = &fitipower_fw050_720_1280_4lane_cmd_list[0];
		num_of_param = ARRAY_SIZE(fitipower_fw050_720_1280_4lane_cmd_list);
	}
	for (i = 0; i < num_of_param; i++)
	{
		ret = ops->cmd_write(dsi,  param_list[i]);
		if (ret < 0)
			return ret;
	}
	return ret;
}

static int panel_dev_set_sequence(struct mipi_dsim_lcd_device *dsim_dev)
{
	int ret = 0;
	struct fw050_panel_dev *panel_dev = fw050_to_panel(dsim_dev);
	PANEL_DEBUG_MSG("enter %s %d \n",__func__, __LINE__);

	if (!panel_dev)
		return -ENODEV;

	ret = panel_dev_panel_init(panel_dev);
	panel_dev_sleep_out(panel_dev);
	msleep(120);
	panel_dev_display_on(panel_dev);
	msleep(5);

	panel_dev->power = FB_BLANK_UNBLANK;
	return ret;
}


