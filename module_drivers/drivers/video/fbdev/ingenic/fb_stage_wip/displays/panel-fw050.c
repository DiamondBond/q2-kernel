static int of_panel_parse(struct device *dev)
{
	struct fw050_panel_dev *panel_dev = dev_get_drvdata(dev);
	struct device_node *np = dev->of_node;
	enum of_gpio_flags flags;
	PANEL_DEBUG_MSG("enter %s %d \n",__func__, __LINE__);

	/* 这里只解析 GPIO，真正申请放到读 ID/点屏阶段，支持多个候选 panel 共存。 */
	panel_dev->rst.gpio = of_get_named_gpio_flags(np, "ingenic,rst-gpio", 0, &flags);
	if(gpio_is_valid(panel_dev->rst.gpio)) {
		panel_dev->rst.active_level = (flags & OF_GPIO_ACTIVE_LOW) ? 0 : 1;
	} else {
		dev_warn(dev, "invalid gpio rst.gpio: %d\n", panel_dev->rst.gpio);
	}

	panel_dev->vdd_en.gpio = of_get_named_gpio_flags(np, "ingenic,vdd-en-gpio", 0, &flags);
	if(gpio_is_valid(panel_dev->vdd_en.gpio)) {
		panel_dev->vdd_en.active_level = (flags & OF_GPIO_ACTIVE_LOW) ? 0 : 1;
	} else {
		dev_warn(dev, "invalid gpio vdd_en.gpio: %d\n", panel_dev->vdd_en.gpio);
	}

	panel_dev->lcd_pwm.gpio = of_get_named_gpio_flags(np, "ingenic,lcd-pwm-gpio", 0, &flags);
	if(gpio_is_valid(panel_dev->lcd_pwm.gpio)) {
		panel_dev->lcd_pwm.active_level = (flags & OF_GPIO_ACTIVE_LOW) ? 0 : 1;
	} else {
		dev_warn(dev, "invalid gpio lcd-pwm.gpio: %d\n", panel_dev->lcd_pwm.gpio);
	}

	return 0;
}

