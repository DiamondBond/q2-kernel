static int of_lcd_panel_parse(struct st7735s_plat_data *lcd_panel)
{
	struct device *dev = &lcd_panel->spi->dev;
	struct device_node *np = dev->of_node;
	int ret = 0;
#define PANEL_GPIO_GET(gpiodesc,name) do{								\
	if(ret == 0) {													\
		gpiodesc = devm_gpiod_get_optional(dev,name, GPIOD_ASIS); \
		if(IS_ERR_OR_NULL(gpiodesc))							\
		{														\
			gpiodesc = NULL;									\
			ret = -1;											\
			dev_err(dev,"Failed to request %s!\n",name);		\
		}														\
	}															\
}while(0)
	PANEL_GPIO_GET(lcd_panel->rst,"ingenic,rst");
	PANEL_GPIO_GET(lcd_panel->dcx,"ingenic,lcd-dcx");

	return ret;
	}

static int st7735s_probe(struct spi_device *spi)
{
	int ret;
	struct st7735s_plat_data *plat_data;
	printk("-------------------st7735s_probe begin!!!!\n");

	/* setup spi related info */
	spi->bits_per_word = 8;
	spi->mode = SPI_MODE_1;
	ret = spi_setup(spi);
	if (ret < 0) {
		dev_err(&spi->dev, "spi setup failed %d", ret);
		return ret;
	}

	plat_data = devm_kzalloc(&spi->dev,sizeof(*plat_data), GFP_KERNEL);
	if (plat_data == NULL)
		return -ENOMEM;

	plat_data->spi = spi;

	plat_data->mdev.minor = MISC_DYNAMIC_MINOR;
	plat_data->mdev.name = DRV_NAME;
	plat_data->mdev.fops = &lcd_misc_fops;

	ret = of_lcd_panel_parse(plat_data);

	if(ret == 0) {
		RESET(plat_data,0);
		ret = Initial_IC(plat_data);
#if 1
		Lcd_Fill(plat_data,0,0,LCD_W,LCD_H,0xFFE0);
		udelay(2000);
		Lcd_Fill(plat_data,0,0,LCD_W,LCD_H,0x0000);
		udelay(2000);
		Lcd_Fill(plat_data,0,0,LCD_W,LCD_H,0x07E0);
		udelay(2000);
		Lcd_Fill(plat_data,0,0,LCD_W,LCD_H,0x001F);
		udelay(2000);
		Lcd_Fill(plat_data,0,0,LCD_W,LCD_H,0xFFFF);
		udelay(2000);
#ifdef HORIZONTAL
		Lcd_Show_Pic(plat_data,60,44,40,40,gImage_1);
#else
		Lcd_Show_Pic(plat_data,44,60,40,40,gImage_1);
#endif
#endif
		ret = ret || misc_register(&plat_data->mdev);
		if (ret < 0) {
			dev_err(&spi->dev,"lcd misc_register failed\n");
			ret = -EINVAL;
		}
	}

	printk("-------------------st7735s_probe end!!!! %s\n",ret == 0 ? "OK" : "ERROR");
	return ret;
}

