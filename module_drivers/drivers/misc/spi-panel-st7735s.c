static int SPI_WriteCommand(struct st7735s_plat_data *plat,uint8_t cmd)
{
	int ret;
	DCX(plat,0);
	ret = spi_write(plat->spi,&cmd,1);
	if (ret < 0) {
		pr_err("SPI Write failed: %d\n", ret);
		return ret;
	}
	DCX(plat,1);
	return ret;
}

static int SPI_WriteData(struct st7735s_plat_data *plat,uint8_t data)
{
	int ret;
	ret = spi_write(plat->spi,&data,1);
	if (ret < 0) {
		pr_err("SPI Write failed: %d\n", ret);
		return ret;
	}
	return 0;
}

static int SPI_WriteData_16(struct st7735s_plat_data *plat,uint16_t data)
{
	data = cpu_to_be16(data);
	return spi_write(plat->spi, &data, 2);
}

static void Lcd_Address_Set(struct st7735s_plat_data *plat,uint16_t x1,uint16_t y1,uint16_t x2,uint16_t y2){
	SPI_WriteCommand(plat,0x2a);
	SPI_WriteData_16(plat,x1);
	SPI_WriteData_16(plat,x2);

	SPI_WriteCommand(plat,0x2b);
	SPI_WriteData_16(plat,y1);
	SPI_WriteData_16(plat,y2);

	SPI_WriteCommand(plat,0x2c);
}

static void Lcd_Fill(struct st7735s_plat_data *plat,uint16_t x_sta,uint16_t y_sta,uint16_t x_end,uint16_t y_end,const uint16_t color ){
	uint16_t i,j;
	Lcd_Address_Set(plat,x_sta,y_sta,x_end,y_end);
	for(i=y_sta;i<y_end;i++){
		for(j=x_sta;j<x_end;j++){
			SPI_WriteData_16(plat,color);
		}
	}

}

static void Lcd_Show_Pic(struct st7735s_plat_data *plat,uint16_t x_sta,uint16_t y_sta,uint16_t len,uint16_t wid,const uint8_t pic[]){
	uint8_t i,j;
	uint32_t k = 0;
	Lcd_Address_Set(plat,x_sta,y_sta,x_sta+len-1,y_sta+wid-1);
	for(i=0;i<len;i++){
		for(j=0;j<wid;j++){
			SPI_WriteData(plat,pic[k*2]);
			SPI_WriteData(plat,pic[k*2+1]);
			k++;
		}
	}

}

